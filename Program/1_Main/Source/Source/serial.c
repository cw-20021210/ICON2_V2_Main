/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	serial 수신 INTERRUPT
 *----------------------------------------------------------------------------
 * 기      능 :	수신 data check
 송수신 mode check
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
void R_Serial_Interrupt(void)
{
	U8 recdata;
	/****************************************************/
	recdata = RecdataRead(); /*	수신data의 읽기*/

	if ((gu8_SerControl & 0xf0) != 0x20)
	{ /*	수신 이외인 경우*/
		return; /*		DATA 파기*/
	}

	switch (recdata)
	{ /*	switch (수신data)*/
		case Z_STXcode: /*	[STX:0x02]인 경우*/
			gu8_CounterSerData = 0; /*		serial 통신 counter clr*/
			break;
		case 0x00:
		case 0xff: /*	dead code인 경우*/
			return; /*		data 파기*/
//		break;
		default: /*	상기이외*/
			break;
	}

	if (gu8_SerControl > 0x26)
	{ /*	상태가 없는 경우*/
		SafetyLoop(); /*		Safety Loop*/
	}
	SerReceive(recdata); /*	통상 수신*/
	/*	*/
}

