/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	30:송신 대기 [data 준비 check]
 *----------------------------------------------------------------------------
 * 기      능 :	F3 command, B1 command의 송신data 준비상황을 check
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	0:미준비, 1:준비
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 DataReadyCheck(void) /*	data ready check*/
{
	/****************************************************/
	switch (gu8_BufferSerData[1])
	{ /*	switch (CMD1)*/
		case 0xf3: /*	[F3] command의 경우*/
			if (gu8_R_eepSerial == 0x01)
			{ /*		EEPROM 읽기 = OK의 경우*/
				return (1); /*			송신 DATA 준비 완료*/
			} else if (gu8_R_eepSerial == 0x00)
			{ /*		EEPROM 읽기 = NG의 경우*/
				gu8_SerControl = 0x00; /*			송신 중지*/
			} else
			{
			}
			break;
		case 0xb1: /*	[B1] command의 경우*/
			if (gu8_B1cmdAns == 0)
			{ /*		ANSWER 이상 확정의 경우*/
				return (1); /*			송신data 준비 완료*/
			} else if ((gu8_R_eepSerial == 0x01) || (gu8_R_eepSerial == 0x00))
			{
				/*		EEPROM 처리 종료의 경우*/
				gu8_B1cmdAns = gu8_R_eepSerial; /*			ANSWER에 결과를 COPY*/
				return (1); /*			송신 DATA 준비 완료*/
			} else
			{
			} /*			송신data 준비 완료*/
			break;
		default: /*	송신 DATA 준비 대기 필요없는 커멘드의 경우*/
			return (1); /*		송신data 준비 완료*/
			break;
	}
	return (0); /*	송신data 준비 미완료*/
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	data 전송
 *----------------------------------------------------------------------------
 * 기      능 :	data수분, 전송 원부터 전송 선으로 data를 전송
 *----------------------------------------------------------------------------
 * 인      수 :	U8 *pmoto (전송 선)
 U8 *psaki (전송 원)
 U8 size (DATA 수)
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void TraDataStore(U8 *pmoto, U8 *psaki, U8 size)
{
	/****************************************************/
	for (; size != 0; size--)
	{ /*	for Loop (data수)	  */
		*psaki = *pmoto; /*		DATA 전송		  */
		psaki++; /*		전송 선ADDRESS +1 */
		pmoto++; /*		전송 원ADDRESS +1 */
	}
}
