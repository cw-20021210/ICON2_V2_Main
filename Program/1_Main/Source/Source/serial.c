/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	통신 상태 천이 [10 : 표준 수신]
 *----------------------------------------------------------------------------
 * 기      능 :	수신완료를 check
 - 수신data check와 command check가 ok인 경우 송신 대기로 이행
 - 상기의 check가 ng인 경우 수신 대기로 이행
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void SerStdRecieve(void) /*	표준 수신*/
{
	/****************************************************/
	if (gu8_SerControl == 0x00)
	{ /*	수신완료인 경우*/
		if (RecDataCheck() == 1)
		{ /*		수신data check가 OK인 경우*/
			if (Command() == 1)
			{ /*			각 command 처리가 정상인 경우*/
				Go_StdTransmit(); /*				송신 대기 초기 설정*/
			} else
			{ /*			command 처리가 이상인 경우*/
				Go_StdRecieve(); /*				수신 대기 초기 설정*/
			}
		} else
		{ /*		수신code가 이상인 경우*/
			Go_StdRecieve(); /*			수신 대기 초기 설정*/
		}
	}
}

