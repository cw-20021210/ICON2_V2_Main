/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	송신 data의 set [STX ~ CMDn]
 *----------------------------------------------------------------------------
 * 기      능 :	송신 buffer에 STX~CMDn의 data를 write
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	U8 data (송신data:STX~CMDn)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U16 SerTra_STXCMD(void) /*	송신 처리 (STX ~ CMDn)*/
{
	U16 data;
	/****************************************************/
	data = gu8_BufferSerData[gu8_CounterSerData]; /*	수신 buffer data*/
	gu8_CounterSerData++;
	if (gu8_CounterSerData >= gu8_CMDMany)
	{ /*	지정data수 송신 종료한 경우*/
		if (gu8_DataMany == 0)
		{ /*		[DATA1~DATAn] 송신 필요없는 경우*/
			gu8_SerControl = 0x42; /*			serial송수신상태 -> 송신:[ETX]*/
		} else
		{ /*		[DATA1~DATAn] 송신 필요있는 경우*/
			gu8_SerControl = 0x41; /*			serial송수신상태 -> 송신:[DATA1~DATAn]*/
			TraDataStore(gu16_access.pnt, &gu8_DataNum[0], gu8_DataMany);
			/*			송신 DATA 임시 저장*/
			F_ascii = Z_asciihi; /*			상위부터 송신*/
			gu8_CounterSerData = 0; /*			serial송신 counter clr*/
		}
	}

	return (data); /*	반환값=[송신data]*/
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	송신 data의 set [DATA1 ~ DATAn]
 *----------------------------------------------------------------------------
 * 기      능 :	송신 buffer에 DATA1~DATAn의 data를 write
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	U8 data (송신data:DATA1~DATAn)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U16 SerTra_DATA(void) /*	송신 처리 (DATA1 ~ DATAn)*/
{
	U16 data;
	/****************************************************/
	data = Ascii(gu8_DataNum[gu8_CounterSerData], F_ascii); /*	송신 data (ASCII 변환)*/
	if (F_ascii == Z_asciilo)
	{ /*	하위4BIT data 송신인 경우*/
		F_ascii = Z_asciihi; /*		다음 상위 송신*/
		gu8_CounterSerData++;
		if (gu8_CounterSerData >= gu8_DataMany)
		{ /*		지정data수 송신 종료한 경우*/
			gu8_SerControl = 0x42; /*			serial송수신상태 -> 송신:[ETX]*/
		}
	} else
	{ /*	상위 송신인 경우*/
		F_ascii = Z_asciilo; /*		다음 하위 송신*/
	}

	return (data); /*	반환값=[송신data]*/
}

