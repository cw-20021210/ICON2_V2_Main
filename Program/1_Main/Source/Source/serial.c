/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	수신 data check [표준 수신용]
 *----------------------------------------------------------------------------
 * 기      능 :	ETX check
 SUM check
 STX ~ CMDn의 data수 check
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	0:이상, 1:정상
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 RecDataCheck(void) /*	수신 data check*/
{
	U8 sum1 = 0;
	U8 sum2;
	U8 i;
	/****************************************************/
	for (i = 1; i < (Z_recbufmax-1); i++)
	{ /*	for 루프(수신data 버퍼분)*/
		sum1 += gu8_BufferSerData[i]; /*		checksum치 가산*/
		if (gu8_BufferSerData[i] == Z_ETXcode)
		{ /*		[ETX] data인 경우*/
			gu8_CMDMany = i; /*			[STX~CMD3] 송신data수 set*/
			if (DisAsciiByte(&gu8_BufferSerData[i + 1], &sum2) == 1)
			{
				/*		ASCII역변환(checksum치) 정상인 경우*/
				if (sum1 == sum2)
				{ /*				checksum치 정상인 경우*/
					return (1); /*					수신 data 정상*/
				}
			}
			return (0); /*			수신 data 이상*/
		}
	}
	return (0); /*	[ETX] 미수신 (수신 data 이상)*/
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	송수신 관리
 *----------------------------------------------------------------------------
 * 기      능 :	송수신 상태를 각각 관리한다.
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void SerTxRxControl(void) /*	송수신 관리*/
{
	/****************************************************/
	switch (gu8_SerControl & 0xf0)
	{ /*	switch(송수신 상태)*/
		case 0x00: /*	대기인 경우*/
			break;
		case 0x10: /*	수신대기인 경우*/
			SerRcvWait(); /*		[10 수신대기]*/
			break;
		case 0x20: /*	수신(MAIN처리는 없음)인 경우*/
			break;
		case 0x30: /*	송신대기인 경우*/
			SerTraWait(); /*		[30 송신대기]*/
			break;
		case 0x40: /*	송신인 경우*/
			SerTransmit(); /*		[40 송신처리]*/
			break;
		default: /*	상기 이외인 경우*/
			break;
	}
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	송수신 관리 [10 : 수신 대기]
 *----------------------------------------------------------------------------
 * 기      능 :	송신 간격 timer를 check하여 신규 수신 data를 기다린다.
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void SerRcvWait(void) /*	수신 대기*/
{
	/****************************************************/
	if (gu8_TimerSerTrIntvl == 0)
	{ /*	Character 간격 timer up인 경우*/
//		SERIAL_SFRRFS(); /*		송수신금지 & SFR REFRESH*/
		R_UART1_Create();
		gu8_CounterSerData = 0; /*		Serial 송수신 counter clr*/
		gu8_SerControl = 0x20; /*		상태천이 -> 표준수신*/
//		SERIAL_RX0EN(); /*		수신허가 송신금지*/
		R_UART1_Start();
	}
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	송수신 관리 [30 : 송신 대기]
 *----------------------------------------------------------------------------
 * 기      능 :	송신 금지 timer를 check
 - 송신data 준비 check하여 송신
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void SerTraWait(void) /*	송신 대기*/
{
	/****************************************************/
	if (gu8_TimerSerTrNo == 0)
	{ /*	송신 금지 timer up인 경우*/
//		SERIAL_SFRRFS()
		R_UART1_Create(); /*		송신금지 & SFR REFRESH*/
		if (DataReadyCheck() == 1)
		{ /*		DATA준비check ok인 경우*/
			gu8_CounterSerData = 0; /*			serial 송수신 counter clear*/
			gu8_BufferChecksum = 0x00;
			gu8_SerControl = 0x40; /*			상태천이 -> 송신*/
			SERIAL_TX0EN(); /*			송신허가 & 수신금지*/
			R_UART1_Start();
		}
		else
		{ /*		DATA준비check NG인 경우*/
			if (gu8_TimerSerCmuSts == 0)
			{ /*			송신대기시간(5s) 경과한 경우*/
				gu8_SerControl = 0x00; /*				상태천이 -> 송수신대기 (송신cancel)*/
			}
		}
	}
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	송수신 관리 [40 : 송신 처리]
 *----------------------------------------------------------------------------
 * 기      능 :	character 간격 timer up check하여 송신data set
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void SerTransmit(void) /*	송신 처리*/
{
	/****************************************************/
	if ((SSR00 & 0x07) == 0)
	{ /*	error가 없는 경우*/
		if (gu8_TimerSerTrIntvl == 0)
		{ /*		serial character 간격 timer up인 경우*/
			TransDataSet(); /*			serial 송신 data set*/
			gu8_TimerSerTrIntvl = ZT_serTrIntvl; /*			serial character 간격 timer set*/
		}
	}
}

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :	40 : 송신 처리 [송신 data set]
 *----------------------------------------------------------------------------
 * 기      능 :	각 송신 상태에 따른 data의 설정
 - STX ~ CR
 *----------------------------------------------------------------------------
 * 인      수 :	-
 *----------------------------------------------------------------------------
 * 반  환  값 :	-
 *----------------------------------------------------------------------------
 * 주의  사항 :	-
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static void TransDataSet(void) /*	송신 data set*/
{
	U8 tradata;
	/****************************************************/
	switch (gu8_SerControl)
	{ /*	switch (serial 송수신 상태)*/
		case 0x40: /*	[STX~CMD3]인 경우*/
			tradata = (U8) SerTra_STXCMD(); /*		[STX~CMD3] 송신 DATA*/
			gu8_BufferChecksum += tradata; /*		CHECKSUM 가산*/
			break;
		case 0x41: /*	[DATA1~DATAn]인 경우*/
			tradata = (U8) SerTra_DATA(); /*		[DATA1~DATAn] 송신 DATA*/
			gu8_BufferChecksum += tradata; /*		CHECKSUM 가산*/
			break;
		case 0x42: /*	[ETX]인 경우*/
			tradata = (U8) SerTra_ETX(); /*		[ETX] 송신 DATA*/
			gu8_BufferChecksum += tradata; /*		CHECKSUM 가산*/
			gu8_BufferChecksum = (U8) (gu8_BufferChecksum - Z_STXcode);     //			CHECKSUM 산출 버퍼 초기화([STX]분 감하여둔다)
			break;
		case 0x43: /*	[SUM1,SUM2]인 경우*/
			tradata = (U8) SerTra_SUM(); /*		[SUM1,SUM2] 송신 DATA*/
			break;
		case 0x44: /*	[CR]인 경우*/
			tradata = (U8) SerTra_CR(); /*		[CR] 송신 DATA*/
			break;
		default: /*	상기이외의 경우*/
			return; /*		return*/
			break;
	}


	TraDataWrite((U8) tradata); /*	송신 레지스터에 data write*/
}

