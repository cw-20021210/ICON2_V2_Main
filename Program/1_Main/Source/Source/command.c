/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :  표준 SERIAL COMMAND 분석
 *----------------------------------------------------------------------------
 * 기      능 :  -
 *----------------------------------------------------------------------------
 * 인      수 :  -
 *----------------------------------------------------------------------------
 * 반  환  값 :  0 (COMMAND 실행 있음-이상종료)
 1 (COMMAND 실행 있음-정상종료)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
U8 Command(void)									//
{														//
	U8 ret = 0;									//	초기치[0:이상종료]
	//---------------------------------					//
	if (F_TestMode_PBA == SET)
	{ /*	TEST MODE인 경우 		*/
		gu8_TimerTestMode = ZT_TestMode; /*		serial command 미수신 timer set */
	}													//
	C_nest = 0x00;										//	재귀횟수 초기 CLR
	ret = CommandCheck(cmd1data, 1);						//	CMD1 CHECK
	if ((ret == 1) && (gu8_BufferSerData[1] == 0xF7))
	{			//	정상 and F7 CMD 수신인 경우
		f_F7cmd = 1;								//		F7 CMD 수신 FLAG SET
	}													//
	else
	{												//	이상 or F7 CMD 수신이외의 경우
		f_F7cmd = 0;								//		F7 CMD 수신 FLAG CLR
	}													//
	return (ret);										//	반환값 SET
}														//

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :  표준 SERIAL COMMAND CHECK
 *----------------------------------------------------------------------------
 * 기      능 :  -
 *----------------------------------------------------------------------------
 * 인      수 :  -
 *----------------------------------------------------------------------------
 * 반  환  값 :  0 (이상종료)
 1 (정상종료)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 CommandCheck(CMD_PARA *selcmd, U8 bufno)
{														//
	//----------------------------------				//
	C_nest++;
	if (C_nest > Z_nestMax)
	{							//	재귀이상의 경우
		return (0);										//		반환값=0 (이상종료)
	}													//
														//
	for (; selcmd->name != Z_endcode ; selcmd++)
	{ /*	for loop (대응 CMD 검색)*/
		if (selcmd->name == gu8_BufferSerData[bufno])
		{ /*		대응 CMD 있는 경우*/
			if ((selcmd->cmdsize == 0) || (selcmd->cmdsize == gu8_CMDMany - 1))
			{
				//			CMD수 정상인 경우
				return ((selcmd->exeadr)());		//				반환값=CMD실행결과
			}
			else
			{									//			CMD수 이상인 경우
				return (0);							//				반환값=0 (이상종료)
			}											//
		}												//
	}													//
	return (0);											//	반환값=0 (이상종료)
}														//

