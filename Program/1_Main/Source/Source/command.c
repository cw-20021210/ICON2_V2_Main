/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :  표준 SERIAL 통신 [F6]
 *----------------------------------------------------------------------------
 * 기      능 :  RAM 읽기
 *----------------------------------------------------------------------------
 * 인      수 :  -
 *----------------------------------------------------------------------------
 * 반  환  값 :  0 = COMMAND 실행 없음 (이상종료)
 1 = COMMAND 실행 있음 (정상종료)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 CommandF6(void)								//
{														//
	//---------------------------------					//
	if (DisAsciiByte(&gu8_BufferSerData[6], &gu8_DataMany) == 0)
	{	//	ASCII CODE 역변환(읽기DATA수) 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	if (gu8_DataMany == 0x00)
	{							//	읽기 DATA수 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	if (DisAsciiWord(&gu8_BufferSerData[2], &gu16_access.adr) == 0)
	{
		//	ASCII CODE 역변환(읽기개시RAM ADDRESS:2BYTE) 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	if (((gu16_access.adr + (U16) gu8_DataMany - 1) > Z_rammax)
			|| (gu16_access.adr < Z_rammin))
	{
		//	읽기 RAM ADDRESS 이상(영역 외)인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
														//
	return (1);									//	반환값=[1:COMMAND실행있음(정상종료)]
}														//

