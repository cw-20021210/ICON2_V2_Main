/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :  표준 SERIAL 통신 [F8]
 *----------------------------------------------------------------------------
 * 기      능 :		RAM 쓰기2
 *----------------------------------------------------------------------------
 * 인      수 :  -
 *----------------------------------------------------------------------------
 * 반  환  값 :  0 = COMMAND 실행 없음 (이상종료)
 1 = COMMAND 실행 있음 (정상종료)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 CommandF8(void)								//
{														//
	U16 f8address;									//
	U8 f8data;										//
	//---------------------------------					//
	if (f_F7cmd == 0)
	{
		return (0);
	}

	if (DisAsciiWord(&gu8_BufferSerData[2], &f8address) == 0)
	{
		return (0);
	}
	if (f8address != gu16_access.adr)
	{
		return (0);
	}

	if (DisAsciiByte(&gu8_BufferSerData[6], &f8data) == 0)
	{
		return (0);
	}
	if (f8data != D_F7data)
	{
		return (0);
	}

	*gu16_access.pnt = D_F7data;
	gu8_DataMany = 0;
	return (1);
}

