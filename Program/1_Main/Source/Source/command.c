/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :  표준 SERIAL 통신 [50]
 *----------------------------------------------------------------------------
 * 기      능 :  -
 *----------------------------------------------------------------------------
 * 인      수 :  -
 *----------------------------------------------------------------------------
 * 반  환  값 :  0 = COMMAND 실행 없음 (이상종료)
 1 = COMMAND 실행 있음 (정상종료)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 Command50(void)								//
{														//
	U8 ret = 0;								//	반환값 초기치=[0:COMMAND실행없음(이상종료)]
	U8 i;											//
	U8 numvalue;										//
	U16 address;									//
	U8 position;									//
	//---------------------------------					//
	if (DisAsciiByte(&gu8_BufferSerData[8], &numvalue) == 0)
	{		//	ASCII CODE 역변환(송신BYTE수) 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	if ((numvalue == 0) || (numvalue > Z_50bytemax))
	{				//	송신BYTE수 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
														//
	D_50byte = numvalue;								//	50/51 CMD 송신 BYTE수
	gu8_DataMany = D_50byte;	//	[DATA1~DATAn]송신DATA바이트수:1바이트=ASCII DATA 2회 송신
	//
	if (DisAsciiWord(&gu8_BufferSerData[2], &address) == 0)
	{	//	ASCII CODE 역변환(읽기RAM ADDRESS:2Byte) 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	gu16_addr.adr = address;								//	읽기 RAM ADDRESS
	if ((gu16_addr.adr > Z_rammax) || (gu16_addr.adr < Z_rammin))
	{
		//	읽기 RAM ADDRESS 이상(RAM영역외)인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
														//
	if (DisAsciiByte(&gu8_BufferSerData[6], &position) == 0)
	{    //	ASCII CODE 역변환(송신 위치) 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	if ((position > D_50byte) || (position == 0))
	{		//	송신위치 이상인 경우
		return (0);							//		반환값=[0:COMMAND실행없음(이상종료)]
	}													//
	if (f_50cmd == 0)
	{									//	초회 수신시인 경우
		f_50cmd = 1;								//		50 CMD 수신 FLAG SET
		for (i = 0 ; i < Z_50bytemax ; i++)
		{				//		ADDRESS 초기치 설정
			B_50adr[i] = (U8*) Z_rammin;	//			USER RAM  선두 ADDRESS로 설정
		}												//
	}													//
	B_50adr[position - 1] = gu16_addr.pnt;					//	송신 DATA ADDRESS
	ret = Command51();									//	송신 DATA 설정
	return (ret);										//	반환값 SET
}														//

/*""FUNC COMMENT""***********************************************************
 * 함수  개요 :  표준 SERIAL 통신 [51]
 *----------------------------------------------------------------------------
 * 기      능 :  -
 *----------------------------------------------------------------------------
 * 인      수 :  -
 *----------------------------------------------------------------------------
 * 반  환  값 :  0 = COMMAND 실행 없음 (이상종료)
 1 = COMMAND 실행 있음 (정상종료)
 *----------------------------------------------------------------------------
 *""FUNC COMMENT END""*******************************************************/
static U8 Command51(void)								//
{														//
	U8 ret = 0;								//	반환값 초기치=[0:COMMAND실행없음(이상종료)]
	U8 i;											//
	//---------------------------------					//
	if (f_50cmd == 1)
	{									//	50 CMD 수신 경험 있는 경우
		ret = 1;							//		반환값=[1:COMMAND실행있음(정상종료)]
		gu16_access.pnt = &B_50data[0];					//		읽기 ADDRESS
		gu8_DataMany = D_50byte;	//		[DATA1~DATAn]송신DATA바이트수:1바이트=ASCII DATA 2회 송신
		for (i = 0 ; i < D_50byte ; i++)
		{					//		for loop (송신 BYTE 횟수)
			B_50data[i] = *B_50adr[i];	//			지정ADDRESS DATA 송신BUFFER 격납
		}												//
	}													//
														//
	return (ret);										//	반환값 SET
}														//

